package ch01_variable_operator;

public class 문제1 {
    public static void main(String[] args) {

        // 변수 정의, 대입
        int a = 3 ;
        int b = 4 ;
        int c = 5 ;
        int result = 2*a + 3*b - c;

        //출력
        System.out.println("a : " + a);
        System.out.println("b : " + b);
        System.out.println("c : " + c);
        System.out.println("result :  " + result);
    }
}

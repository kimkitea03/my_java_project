package ch01_variable_operator;

public class ms6 {
    public static void main(String[] args) {
        int x = 5 ;

        x +=  3 ; // x = x + 3 이거랑 같음
        System.out.println("x : " + x);

        x *= 4 ; // x = x * 4
        System.out.println("x : " + x);

        x %= 5 ; // x = x % 5
        System.out.println("x : " + x);

        x -= 1 ; // x = x - 1
        System.out.println("x : " + x);

        x += 7 ; // x = x+ 7
        System.out.println("x : " + x);
    }
}
